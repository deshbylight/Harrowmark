"""Generate LODs for the detective CH01 (run: jf uepy Tools/ue/ch01_lods.py).

LOD0 is the 361k-triangle Tripo mesh. In first person the game draws two copies (world body + view body),
so LOD1 (~1/3, ~120k) and LOD2 (~1/9, ~40k) are generated by the engine's skeletal mesh reduction,
driven by a LOD settings asset so a reimport keeps them. Prints JF_LODS lines; idempotent.
"""
import unreal

MESH = "/Game/Characters/Detective/SK_CH01_Detective/SkeletalMeshes/SK_CH01_Detective"
SETTINGS_DIR = "/Game/Characters/Detective/SK_CH01_Detective/SkeletalMeshes"
SETTINGS_NAME = "LODS_CH01_Detective"
# (screen size, share of LOD0 triangles)
LODS = [(1.0, 1.0), (0.5, 0.33), (0.25, 0.11)]


def main():
    mesh = unreal.load_asset(MESH)
    sub = unreal.get_editor_subsystem(unreal.SkeletalMeshEditorSubsystem)
    path = f"{SETTINGS_DIR}/{SETTINGS_NAME}"
    lods = unreal.load_asset(path) if unreal.EditorAssetLibrary.does_asset_exist(path) else None
    if lods is None:
        factory = unreal.DataAssetFactory()
        factory.set_editor_property("data_asset_class", unreal.SkeletalMeshLODSettings)
        lods = unreal.AssetToolsHelpers.get_asset_tools().create_asset(
            SETTINGS_NAME, SETTINGS_DIR, unreal.SkeletalMeshLODSettings, factory)
        if lods is None:
            raise RuntimeError(f"could not create {path}")

    groups = []
    for screen, share in LODS:
        g = unreal.SkeletalMeshLODGroupSettings()
        g.set_editor_property("screen_size", unreal.PerPlatformFloat(default=screen))
        r = g.get_editor_property("reduction_settings")
        r.set_editor_property("termination_criterion",
                              unreal.SkeletalMeshTerminationCriterion.SMTC_NUM_OF_TRIANGLES)
        r.set_editor_property("num_of_triangles_percentage", share)
        g.set_editor_property("reduction_settings", r)
        groups.append(g)
    lods.set_editor_property("lod_groups", groups)
    unreal.EditorAssetLibrary.save_loaded_asset(lods, False)

    mesh.set_editor_property("lod_settings", lods)
    if not sub.regenerate_lod(mesh, len(LODS), True, False):
        raise RuntimeError("regenerate_lod failed")
    counts = [sub.get_num_verts(mesh, i) for i in range(sub.get_lod_count(mesh))]
    unreal.EditorAssetLibrary.save_loaded_asset(mesh, False)
    print(f"JF_LODS lods={len(counts)} verts={counts}")
    if len(counts) != len(LODS):
        raise RuntimeError("unexpected LOD count")


main()
